#!/usr/bin/env python3
"""D7 evidence classification, not a geometry/physics or feasibility solver.

Standard library; source decisions are explicit below. --write updates only the
D7 generated Markdown. Without arguments, prints the same reproducible report.
"""
from pathlib import Path
import argparse

MODES = {
    'S': ((1,), (2,), (3,), (4,)),
    'R': ((1, 2), (3, 4)),
    'C': ((1, 3), (2, 4)),
    'M12': ((1, 2), (3,), (4,)),
    'M34': ((3, 4), (1,), (2,)),
    'M13': ((1, 3), (2,), (4,)),
    'M24': ((2, 4), (1,), (3,)),
    'J': ((1, 2, 3, 4),),
}
# Codes are independently stated evidence judgments, in MODES order.
# K conditional; U unresolved; D conceivable-at-DOF-only; X unsupported-as-proposed.
XY = {
    'A0': ('Strictly local four stages', 'KXXXXXXX'),
    'A+bridge': ('Extended full-span independently Z-moving bridges', 'UUUUUUUU'),
    'A+cant': ('Independent perimeter tangential/radial stages', 'DDDDDDDD'),
    'B0': ('Four X carriages on one common translating Y beam', 'XXXXXXXU'),
    'B1': ('Independent but nonpassing full-width bridges', 'XKXXXXXU'),
    'B2': ('Fixed overhead stacked bridges with descending columns', 'UUUUUUUU'),
    'B3': ('Common static frame, separate Cartesian/cantilever stages', 'DDDDDDDD'),
    'C0': ('Four strict locals plus independent global fifth', 'KXXUUUUU'),
    'C+': ('Fifth plus at least two locals extended for both pair directions', 'DDDDDDDD'),
    'D0': ('One active full-region toolchanging gantry', 'XXXXXXXU'),
    'D+': ('Automatic stage/beam reconfiguration, independent groups retained', 'UUUUUUUU'),
    'E-only': ('A/B/B/A packaging without an underlying XY mechanism', 'UUUUUUUU'),
}
Z = {
    'A': ('Independent full-stroke head/gantry Z; stationary supported beds', 'KKKKKKKK'),
    'B-raw': ('Independent bed lifts, grouped alignment unspecified', 'KUUUUUUU'),
    'C0': ('Individual S lifts; partial beds locked under one gantry; J gantry Z', 'KXXXXXXK'),
    'C-group': ('Grouped lifts in partial modes; stationary locked beds and gantry Z in J', 'KKKKKKKK'),
    'D-trim': ('Common gantry with genuinely short head trim', 'XXXXXXXK'),
    'E-sync': ('Local lifts with measured group synchronization; no load ties', 'KKKKKKKK'),
    'E-drive': ('Selected phased torque links; local supports and released unused drives', 'KKKKKKKK'),
    'E-tie': ('Cold structural ties with compatible released guides and force sharing', 'KKKKKKKK'),
    'E-hybrid': ('Cold load ties plus monitored master/follower group drives', 'KKKKKKKK'),
    'F0-reroute': ('S lifts, J-only unified platform via belt rerouting; no partial groups', 'KXXXXXXU'),
    'F0-clutch': ('S lifts, J-only unified platform via positive selector; no partial groups', 'KXXXXXXK'),
    'F-group-reroute': ('Retained E-sync partial lifts; isolated J platform; belt rerouting', 'KKKKKKKU'),
    'F-group-clutch': ('Retained E-sync partial lifts; isolated J platform; positive selector', 'KKKKKKKK'),
    'F-attached': ('One rigid frame attached to all beds in every mode', 'XXXXXXXK'),
    'F-row': ('Two permanent rigid row sections as sole printing-Z support', 'XKXXXXXK'),
    'F-section': ('Four independently selectable sections; support topology undefined', 'UUUUUUUU'),
}
GATES = {
    'X': 'A stated functional contradiction; see profile and counterexample ledger.',
    'U': 'Unspecified topology/range or unresolved collision/transfer; requires a concrete mechanism.',
    'D': 'Coordinate ownership can express the mode; geometry/load path not established.',
    'K': 'Conditional on the specified mechanism AND every shared evidence gate; not feasible/proven.',
}

def verdict(xy, z, mode):
    """Conservative conjunction; it never upgrades a subsystem classification."""
    i = list(MODES).index(mode)
    a, b = XY[xy][1][i], Z[z][1][i]
    for status in ('X', 'U', 'D', 'K'):
        if status in (a, b):
            return status
    raise ValueError('unknown status')


def reasons(xy, z, mode):
    i = list(MODES).index(mode)
    return f'XY {xy}:{XY[xy][1][i]}, Z {z}:{Z[z][1][i]}; shared gates G1–G7'


def render():
    out = ['# D7 — complete integrated classification matrix', '',
           'Generated by [d7_matrix.py](d7_matrix.py). Read the [profile contracts and counterexamples](d7-compatibility.md) before using a cell.', '',
           '**Desktop screening only. No cell establishes physical feasibility or permission for CAD.**', '',
           'Each cell is the conservative conjunction of its XY and Z profile, with precedence X > U > D > K. This is an evidence ledger, not a mechanical compatibility theorem. '
           'Cross-system gates G1–G7 apply to every cell, including K. A contradiction dominates uncertainty but does not erase other missing evidence.', '']
    for code, meaning in GATES.items():
        out.append(f'- **{code}**: {meaning}')
    out += ['', '## Eight arrangements', '', '| Mode | Bed groups | Independent job/relative-Z owners | Internal seam edges |', '| --- | --- | --- | --- |']
    edges = ((1, 2), (1, 3), (2, 4), (3, 4))
    for mode, groups in MODES.items():
        seams = [str(a)+str(b) for a, b in edges if any(a in g and b in g for g in groups)]
        out.append(f"| {mode} | {' / '.join(''.join(map(str,g)) for g in groups)} | {len(groups)} | {', '.join(seams) or 'None'} |")
    out += ['', '## XY profiles', '', '| ID | Explicit variant | S | R | C | M12 | M34 | M13 | M24 | J |', '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |']
    for key, (name, codes) in XY.items():
        out.append(f"| {key} | {name} | {' | '.join(codes)} |")
    out += ['', '## Z profiles', '', '| ID | Explicit variant | S | R | C | M12 | M34 | M13 | M24 | J |', '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |']
    for key, (name, codes) in Z.items():
        out.append(f"| {key} | {name} | {' | '.join(codes)} |")
    out += ['', '## Full cross-product', '',
            '12 XY profiles × 16 Z profiles × 8 modes = **1,536 explicit cells**. '
            'For every A–D row, the E overlay is also evaluated: its topological classification is identical, '
            'but it adds G3’s exact A/B/B/A envelope, handed-interface and outer-parking obligations. '
            'This factorization covers both common-orientation and E-overlay cases without pretending E supplies axes. '
            'E-only remains unresolved even with sufficient Z ownership.', '',
            '| XY | Z | S | R | C | M12 | M34 | M13 | M24 | J |',
            '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |']
    for xy in XY:
        for z in Z:
            out.append(f"| {xy} | {z} | {' | '.join(verdict(xy,z,m) for m in MODES)} |")
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    result = render()
    if args.write:
        Path(__file__).with_name('d7-matrix.md').write_text(result, encoding='utf-8')
    else:
        print(result, end='')
